"""Upload one cycle's generated report/ directory via SFTP.

Uses the same [sftp] settings and upload code as ``watch-reports``, for a
report that was generated by hand or needs to be pushed again.
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime
from pathlib import Path

from vewutils.plot.watch_reports import (
    parse_cycle_datetime,
    render_remote_path,
    upload_report,
)


def resolve_cycle_datetime(data_dir: Path, cycle: str | None) -> datetime | None:
    """Return the cycle time from --cycle (YYYYMMDDHH) or the data_dir path."""
    if cycle:
        try:
            return datetime.strptime(cycle, '%Y%m%d%H')
        except ValueError:
            raise ValueError(f'--cycle must be YYYYMMDDHH, got {cycle!r}') from None
    return parse_cycle_datetime(data_dir)


def get_parser():
    parser = argparse.ArgumentParser(
        add_help=False,
        description=(
            'Upload a generated report directory to the host in the config\'s '
            '[sftp] section, the same way watch-reports does after a '
            'successful run. Files with the same name on the remote side are '
            'overwritten; remote files not in the report are left in place.'
        ),
    )
    parser.add_argument(
        '--config',
        required=True,
        help='Report TOML config providing [sftp] (and report.data_dir/output_dir)',
    )
    parser.add_argument(
        '--data-dir',
        help=(
            'Cycle directory (overrides report.data_dir). The report uploaded '
            'is report.output_dir, or <data_dir>/report when that is unset.'
        ),
    )
    parser.add_argument(
        '--report-dir',
        help='Upload this directory instead of the config\'s output_dir',
    )
    parser.add_argument(
        '--cycle',
        metavar='YYYYMMDDHH',
        help=(
            'Cycle time for remote_path_template. Default: parsed from the '
            '.../YYYYMMDD/hour_HH/... part of the data directory path'
        ),
    )
    parser.add_argument(
        '--remote-path',
        help=(
            'Remote directory (overrides [sftp].remote_path_template; '
            'YYYY/YYYYMMDDHH tokens are still substituted)'
        ),
    )
    parser.add_argument(
        '--dry-run',
        action='store_true',
        help='Print the source and destination without connecting',
    )
    return parser


def main(args=None):
    if args is None:
        args = get_parser().parse_args()

    from vewutils.plot.generate_report import load_report_config

    config = load_report_config(args.config, data_dir_override=args.data_dir)
    sftp_cfg = dict(config['sftp'])
    if args.remote_path:
        sftp_cfg['remote_path_template'] = args.remote_path
    if not sftp_cfg.get('remote_path_template'):
        print(
            'Error: no remote path (set [sftp].remote_path_template or pass '
            '--remote-path)',
            file=sys.stderr,
        )
        return 1

    data_dir = Path(config['report']['data_dir'])
    report_dir = (
        Path(args.report_dir).resolve() if args.report_dir
        else Path(config['report']['output_dir'])
    )
    if not (report_dir / 'index.html').is_file():
        print(
            f'Error: {report_dir} has no index.html; run generate-report first',
            file=sys.stderr,
        )
        return 1

    try:
        cycle_dt = resolve_cycle_datetime(data_dir, args.cycle)
    except ValueError as exc:
        print(f'Error: {exc}', file=sys.stderr)
        return 1
    template = sftp_cfg['remote_path_template']
    if cycle_dt is None:
        if 'YYYY' in template:
            print(
                f'Error: cannot tell the cycle time from {data_dir}; pass '
                '--cycle YYYYMMDDHH',
                file=sys.stderr,
            )
            return 1
        # No tokens to substitute, so any time renders the same path.
        cycle_dt = datetime.now()
    remote_dir = render_remote_path(template, cycle_dt)

    host = sftp_cfg.get('host')
    if args.dry_run:
        print(f'Would upload {report_dir} to {host}:{remote_dir}')
        return 0

    uploaded, error = upload_report(sftp_cfg, report_dir, cycle_dt)
    if not uploaded:
        print(f'Error: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
